"""Build storage-sets.json (POH costume room sets and their pieces) from OSRS wiki "<storage> space" pages.

usage: python -I convert_wiki_storage_sets.py <raw wiki dir> <wiki-item-ids.json> <gameval.txt> <out.json> <out.java>

<raw wiki dir> holds the raw wikitext (https://oldschool.runescape.wiki/w/<Page>?action=raw) of:
  Fancy_dress_box_space, Armour_case_space, Magic_wardrobe_space, Cape_rack_space, Treasure_chest_space
<wiki-item-ids.json> comes from fetch_wiki_item_ids.py; <gameval.txt> is a `javap -constants` dump of
net.runelite.api.gameval.ItemID ("NAME = id" per line), so only items the client knows are kept, by gameval name.

Outputs:
  out.json: {"<STORAGE>": [{"set": name, "items": [piece names], "ids": [item ids], "tier": clue tier or null,
             "accomplishment": bool}]}
  out.java: WikiStorageItems, every storable item ID per storage (merged into StorageLocation's lists)
"""
import json
import os
import re
import sys

src, ids_file, gameval_file, out, out_java = sys.argv[1:6]

items_by = {'name': {}, 'page': {}, 'sub': {}}
for it in json.load(open(ids_file, encoding='utf-8')):
	for field in items_by:
		items_by[field].setdefault(it[field].lower(), set()).update(it['ids'])
gameval = {}
for line in open(gameval_file, encoding='utf-8'):
	name, value = line.strip().split(' = ')
	gameval.setdefault(int(value), name)


def resolve(piece):
	"""Wiki piece name (item name, page name, or page#version) -> item IDs the client knows"""
	key = piece.lower()
	ids = items_by['name'].get(key) or items_by['sub'].get(key) or items_by['page'].get(key) or set()
	return sorted(i for i in ids if i in gameval)


PAGES = {
	'FANCY_DRESS_BOX': 'Fancy_dress_box_space',
	'ARMOUR_CASE': 'Armour_case_space',
	'MAGIC_WARDROBE': 'Magic_wardrobe_space',
	'CAPE_RACK': 'Cape_rack_space',
	'TREASURE_CHEST': 'Treasure_chest_space',
}
TIERS = ['beginner', 'easy', 'medium', 'hard', 'elite', 'master']
SKILLS = ['Agility', 'Attack', 'Construct.', 'Cooking', 'Crafting', 'Defence', 'Farming', 'Firemaking', 'Fishing',
	'Fletching', 'Herblore', 'Hitpoints', 'Hunter', 'Magic', 'Mining', 'Prayer', 'Ranging', 'Runecraft', 'Sailing',
	'Slayer', 'Smithing', 'Strength', 'Thieving', 'Woodcutting', 'Woodcut.']
ACCOMPLISHMENT = {s + ' cape' for s in SKILLS} | {'Quest point cape', 'Achievement diary cape', 'Music cape'}

SET_ROW = re.compile(r'^\|\s*\[\[([^\]|]+)(?:\|([^\]]+))?\]\]')
ITEM = re.compile(r'\{\{[Pp]link[pt]?\|([^|}]+)')

result = {}
for storage, page in PAGES.items():
	text = open(os.path.join(src, page + '.txt'), encoding='utf-8').read()
	# Only the item tables, after the build/creation tables
	markers = ('==Armour sets==', '==Magical armour==', '==Capes==', '==Storable rewards==', '[[Beekeeper')
	start = min((text.find(h) for h in markers if text.find(h) >= 0), default=0)
	start = text.rfind('\n', 0, start) + 1
	lines = text[start:].splitlines()
	sets, tier, current = [], None, None
	for line in lines:
		heading = re.match(r'^=+\s*([^=]+?)\s*=+\s*$', line)
		if heading:
			name = heading.group(1).lower()
			if name.startswith('changes') or name.startswith('trivia'):
				break
			tier = next((t for t in TIERS if name.startswith(t)), None) if storage == 'TREASURE_CHEST' else None
			if storage == 'TREASURE_CHEST' and name.startswith('not stor'):
				tier = 'skip'
			continue
		row = SET_ROW.match(line)
		if row:
			current = {'set': (row.group(2) or row.group(1)).strip(), 'items': [], 'tier': tier,
				'accomplishment': storage == 'CAPE_RACK' and row.group(1).strip() in ACCOMPLISHMENT}
			if tier != 'skip':
				sets.append(current)
			continue
		if current is not None and ITEM.search(line):
			for name in ITEM.findall(line):
				name = name.strip()
				if name not in current['items']:
					current['items'].append(name)
			current = None
	sets = [s for s in sets if s['items']]
	unresolved = []
	for s_ in sets:
		s_['ids'] = sorted({i for name in s_['items'] for i in resolve(name)})
		unresolved += [name for name in s_['items'] if not resolve(name)]
	result[storage] = sets
	if unresolved:
		print(f'  {storage}: {len(unresolved)} piece names with no item ID: {unresolved}')
	print(f"{storage}: {len(sets)} sets, {sum(len(s['items']) for s in sets)} pieces"
		+ (f", accomplishment {sum(s['accomplishment'] for s in sets)}" if storage == 'CAPE_RACK' else '')
		+ (f", tiers {sorted({s['tier'] for s in sets}, key=str)}" if storage == 'TREASURE_CHEST' else ''))

with open(out, 'w', encoding='utf-8', newline='\n') as f:
	json.dump(result, f, ensure_ascii=False, separators=(',', ':'))

java = ['package com.ultimatebank.feature.storagesavings.data;', '', 'import net.runelite.api.gameval.ItemID;', '',
	'/**', ' * Every item each costume room storage holds according to the OSRS Wiki (see docs/attribution.md).',
	' * GENERATED by tools/convert_wiki_storage_sets.py; do not edit. Merged into {@link StorageLocation}.', ' */',
	'final class WikiStorageItems', '{']
for storage, sets in result.items():
	ids = sorted({i for s_ in sets for i in s_['ids']})
	java.append(f'\tstatic final int[] {storage} = {{')
	java += [f'\t\tItemID.{gameval[i]},' for i in ids]
	java += ['\t};', '']
java += ['\tprivate WikiStorageItems()', '\t{', '\t}', '}', '']
with open(out_java, 'w', encoding='utf-8', newline='\n') as f:
	f.write('\n'.join(java))
